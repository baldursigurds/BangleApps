#!/usr/bin/env python3
"""Build the code footrun uploads to the Puck, from ../accel_fifo.js.

accel_fifo.js uses E.compiledC, which the Espruino Web IDE compiles online -
a watch can't. So this does what Espruino's compiler (EspruinoCompiler,
github.com/gfwilliams/EspruinoCompiler) does, with the same gcc flags and
linker script: compile the C for a Cortex-M4, and replace E.compiledC(...)
with the binary and E.nativeCall()s for its functions. The C uses no
Espruino functions, so the binary works on any firmware version.

The result is minified (comments and spaces removed, with the Esprima and
escodegen that come with EspruinoTools, as the Web IDE does), and put into
app.js between the marker lines as two files for the Puck's Storage:
PUCK_JS (footrun.js, the code) and PUCK_BIN (footrun.bin, the compiled C,
base64), with their CRC32s. footrun writes them to the Puck (if they've
changed) and runs eval(require("Storage").read("footrun.js")) - code run
from Storage keeps its functions in flash, and E.nativeCall runs the binary
straight from flash, so it all fits in the Puck's ~33kB of RAM (sent as one
line it doesn't: the line, its parsed functions and the binary all in RAM).

    python3 build.py        # after changing ../accel_fifo.js

Needs arm-none-eabi-gcc, node, and EspruinoTools (npm install -g espruino).
"""

import base64
import json
import os
import re
import struct
import subprocess
import tempfile
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCE = os.path.join(HERE, "..", "accel_fifo.js")
APP = os.path.join(HERE, "app.js")
BEGIN, END = "// BEGIN PUCK_CODE (generated by build.py - don't edit)", "// END PUCK_CODE"

# From EspruinoCompiler: src/compile.js (cortexm4) and inc/linker.ld - except
# libc.a/libm.a/libgcc.a in /DISCARD/, which make ld look for those libraries
# (that may not be installed); with -nostdlib nothing from them is linked anyway
CFLAGS = ("-mlittle-endian -mthumb -mthumb-interwork -mcpu=cortex-m4 -mfloat-abi=softfp -mfpu=fpv4-sp-d16 "
          "-nostdinc -nostdlib -fno-common -fno-exceptions -fdata-sections -ffunction-sections "
          "-flto -fno-fat-lto-objects -Wl,--allow-multiple-definition -fpic -fpie -fpermissive "
          "-fpreprocessed -std=c++17 -Os").split()
LINKER_LD = """ENTRY(entryPoint)
MEMORY { RAM (xrw) : ORIGIN = 0, LENGTH = 100K }
SECTIONS {
  .entrypoint : { . = ALIGN(4); *(.entryPoint) }
  .text : {
    . = ALIGN(4); *(.text) *(.text*) *(.rodata) *(.rodata*)
    . = ALIGN(4); *(.data) *(.data*)
    . = ALIGN(4); *(.bss) *(.bss*) *(COMMON)
    . = ALIGN(4);
  } >RAM
  /DISCARD/ : { *(.ARM.*) *(.comment) }
}
"""


def compile_c(code):
    """JS for E.compiledC(code), as EspruinoCompiler makes it."""
    entry_points, entry_specs = [], []
    for line in code.strip().split("\n"):
        line = line.strip()
        if not line.startswith("//"):
            break
        m = re.match(r"//\s*(\w+)\s+(\w+)\(([^)]*)\)", line)
        if not m:
            raise SystemExit(f"{line!r} isn't a valid argspec")
        entry_points.append(m.group(2))
        entry_specs.append(f"{m.group(1)}({m.group(3)})")
    code += ('\nextern "C" { void *entryPoint[]  __attribute__ ((section (".entrypoint"))) = {(void*)'
             + ",(void*)".join(entry_points) + "};}")
    with tempfile.TemporaryDirectory() as d:
        open(os.path.join(d, "out.cpp"), "w").write(code)
        open(os.path.join(d, "linker.ld"), "w").write(LINKER_LD)
        subprocess.run(["arm-none-eabi-gcc", *CFLAGS, "-T" + os.path.join(d, "linker.ld"),
                        os.path.join(d, "out.cpp"), "-o", os.path.join(d, "out.elf")], check=True)
        undefined = subprocess.run(["arm-none-eabi-nm", "-u", os.path.join(d, "out.elf")],
                                   capture_output=True, text=True, check=True).stdout.strip()
        if undefined:
            raise SystemExit("The C needs functions there's no library for:\n" + undefined)
        subprocess.run(["arm-none-eabi-objcopy", "-O", "binary", os.path.join(d, "out.elf"),
                        os.path.join(d, "out.bin")], check=True)
        binary = open(os.path.join(d, "out.bin"), "rb").read()
    offset = len(entry_points) * 4
    # The binary is read straight from the Puck's flash (Storage is memory mapped)
    src = '(function(){var bin=require("Storage").read("footrun.bin");return{'
    for i, (name, spec) in enumerate(zip(entry_points, entry_specs)):
        addr = struct.unpack_from("<i", binary, i * 4)[0] - offset
        if not addr & 1:
            raise SystemExit(f"{name}'s address {addr} isn't a Thumb address - the build went wrong")
        src += f"{name}:E.nativeCall({addr},{json.dumps(spec)},bin),"
    return src + "};})()", binary[offset:], dict(zip(entry_points, entry_specs))


def minify(js):
    """Comments and spaces removed, as the Web IDE's 'Esprima (offline)' option."""
    root = subprocess.run(["npm", "root", "-g"], capture_output=True, text=True).stdout.strip()
    libs = os.path.join(root, "espruino", "libs", "esprima")
    if not os.path.exists(libs):
        raise SystemExit("Needs EspruinoTools for Esprima/escodegen: npm install -g espruino")
    script = f"""
const esprima = require({json.dumps(os.path.join(libs, "esprima.js"))});
// a browser bundle that sets the global escodegen
require("vm").runInThisContext(require("fs").readFileSync({json.dumps(os.path.join(libs, "escodegen.js"))}, "utf8"));
let code = require("fs").readFileSync(0, "utf8");
const ast = esprima.parse(code, {{ raw: true }});
process.stdout.write(escodegen.generate(ast, {{ format: {{ compact: true, semicolons: true, quotes: "auto",
  indent: {{ style: "" }}, hexadecimal: true, renumber: true, escapeless: false, parentheses: false }} }}));
"""
    return subprocess.run(["node", "-e", script], input=js, capture_output=True, text=True, check=True).stdout


def main():
    src = open(SOURCE).read()
    m = re.search(r"E\.compiledC\(`(.*?)`\)", src, re.S)
    if not m:
        raise SystemExit("No E.compiledC(`...`) in " + SOURCE)
    compiled, binary, functions = compile_c(m.group(1))
    code = src[:m.start()] + compiled + src[m.end():]
    small = minify(code)
    # Check it still parses as JS, one line
    subprocess.run(["node", "--check", "-"], input=small, text=True, check=True)
    app = open(APP).read()
    a, b = app.index(BEGIN), app.index(END)
    if any(ord(ch) > 126 for ch in small):
        raise SystemExit("The minified code has non-ASCII characters")
    gen = ("\nvar PUCK_JS = " + json.dumps(small) + ";"
           + "\nvar PUCK_JS_CRC = " + str(zlib.crc32(small.encode())) + ";"
           + "\nvar PUCK_BIN = " + json.dumps(base64.b64encode(binary).decode()) + "; // base64"
           + "\nvar PUCK_BIN_CRC = " + str(zlib.crc32(binary)) + ";\n")
    app = app[:a + len(BEGIN)] + gen + app[b:]
    open(APP, "w").write(app)
    print(f"C: {len(binary)} bytes of ARM code, functions {functions}")
    print(f"accel_fifo.js: {len(src)} bytes -> footrun.js {len(small)} bytes + footrun.bin {len(binary)} bytes, into {os.path.relpath(APP)}")


if __name__ == "__main__":
    main()
